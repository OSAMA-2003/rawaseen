export function getStaticProjectById(id: string): IProject | undefined {
  return STATIC_PROJECTS.find((p) => p._id === id);
}

export function getStaticProjectBySlug(slug: string): IProject | undefined {
  return STATIC_PROJECTS.find((p) => p.slug === slug || p._id === slug);
}

export function getStaticUnitsByProjectId(projectId: string): IUnit[] {
  return STATIC_UNITS.filter((u) => {
    const pId = typeof u.projectId === "object" ? u.projectId?._id : u.projectId;
    return pId === projectId;
  });
}

export function getStaticUnitById(id: string): IUnit | undefined {
  return STATIC_UNITS.find(
    (u) =>
      u._id === id ||
      u.unitNumber?.toLowerCase() === id.toLowerCase()
  );
}
